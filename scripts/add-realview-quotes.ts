function main() {
  const files = fs.readdirSync(REGIONS_DIR).filter((f) => f.endsWith(".json") && f !== "_template.json");

  let booksWithQuotes = 0;
  let booksWithoutQuotes = 0;

  for (const file of files) {
    const filePath = path.join(REGIONS_DIR, file);
    const content = fs.readFileSync(filePath, "utf-8");
    const data: RegionFile = JSON.parse(content);
    const regionName = data.region;
    const regionMap = quoteMap[regionName];

    if (!regionMap) {
      console.log(`⚠️  No quote mapping for region: ${regionName} (${file})`);
      continue;
    }

    let modified = false;

    for (const book of data.books) {
      if (!book.realViewName) continue; // no pilgrimage → skip

      const quote = regionMap[book.title];
      if (quote !== undefined) {
        if (book.realViewQuote !== quote) {
          book.realViewQuote = quote;
          modified = true;
        }
        booksWithQuotes++;
      } else {
        if (book.realViewQuote === undefined) {
          book.realViewQuote = "";
          modified = true;
        }
        booksWithoutQuotes++;
      }
    }

    if (modified) {
      fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf-8");
      console.log(`✅ Updated: ${file}`);
    } else {
      console.log(`   No changes: ${file}`);
    }
  }

  console.log(`\n📊 Summary:`);
  console.log(`   Books with quotes: ${booksWithQuotes}`);
  console.log(`   Books without quotes: ${booksWithoutQuotes}`);
}

main();
