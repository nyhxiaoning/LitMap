function main() {
  const files = fs.readdirSync(REGIONS_DIR).filter((f) => f.endsWith(".json") && f !== "_template.json");

  let totalBooks = 0;
  let booksWithPilgrimage = 0;

  for (const file of files) {
    const filePath = path.join(REGIONS_DIR, file);
    const content = fs.readFileSync(filePath, "utf-8");
    const data: RegionFile = JSON.parse(content);
    const regionName = data.region;
    const regionMap = pilgrimageMap[regionName];

    if (!regionMap) {
      console.log(`⚠️  No pilgrimage mapping found for region: ${regionName} (${file})`);
      continue;
    }

    let modified = false;

    for (const book of data.books) {
      totalBooks++;
      const pilgrimageName = regionMap[book.title];

      if (pilgrimageName !== undefined) {
        // Book is in the mapping - set realViewName accordingly
        if (book.realViewName !== pilgrimageName) {
          book.realViewName = pilgrimageName;
          modified = true;
        }
        if (pilgrimageName !== "") {
          booksWithPilgrimage++;
        }
      } else {
        // Book not in mapping - preserve existing realViewName if any, otherwise set empty
        if (book.realViewName === undefined) {
          book.realViewName = "";
          modified = true;
        }
      }
    }

    if (modified) {
      fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf-8");
      console.log(`✅ Updated: ${file} (${data.books.length} books)`);
    } else {
      console.log(`   No changes: ${file}`);
    }
  }

  console.log(`\n📊 Summary:`);
  console.log(`   Total books: ${totalBooks}`);
  console.log(`   Books with pilgrimage: ${booksWithPilgrimage}`);
  console.log(`   Books without pilgrimage (fictional/abstract): ${totalBooks - booksWithPilgrimage}`);
}

main();
