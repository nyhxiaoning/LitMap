/**
 * Shared types for data pipeline scripts.
 * Single source of truth — imported by build-data, fetch scripts, etc.
 */

// ---- Region source files (data/regions/*.json) ----

export interface RegionBook {
  title: string;
  author?: string;
  doubanId?: string;
  lat: number;
  lng: number;
  city: string;
  country?: string;
  century: string;
  tags?: string[];
  quote?: string;
  desc?: string;
  isTrajectory?: boolean;
  realViewName?: string;
  realViewUrl?: string;
  path?: PathNode[];
}

export interface RegionFile {
  region: string;
  description?: string;
  bounds?: { minLat: number; maxLat: number; minLng: number; maxLng: number };
  books: RegionBook[];
}

// ---- Path node (trajectory waypoint) ----

export interface PathNode {
  name: string;
  coord: [number, number];
  year: string;
  info: string;
}

// ---- Douban metadata cache (data/douban-cache.json) ----

export interface DoubanEntry {
  doubanId: string;
  title: string;
  author: string;
  publisher: string;
  pubYear: string;
  rating: string;
  summary: string;
  coverLocalPath: string;
  fetchedAt: string;
}

export interface DoubanCache {
  [doubanId: string]: DoubanEntry;
}

// ---- Output book (generated by build-data.ts → src/data/books.ts) ----

export interface OutputBook {
  rank: number;
  id: string;
  sliderVal: number;
  century: string;
  lat: number;
  lng: number;
  country: string;
  city: string;
  title: string;
  author: string;
  color: string;
  coverUrl: string;
  tags: string[];
  quote: string;
  desc: string;
  isTrajectory?: boolean;
  realViewName: string;
  realViewUrl: string;
  path?: PathNode[];
}
